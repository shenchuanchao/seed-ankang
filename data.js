// 经纬度 -> 世界坐标；x 向东，z 向北取负（Three.js 右手系）
function P(lon, lat, y) {
  return [
    (lon - ORIGIN[0]) * SCALE,
    y || 0,
    -(lat - ORIGIN[1]) * SCALE
  ];
}
function XY(lon, lat) {
  return [(lon - ORIGIN[0]) * SCALE, -(lat - ORIGIN[1]) * SCALE];
}

